#!/usr/bin/env python3
"""sqlite -> static HTML agreement/eval board. B6.

Static HTML on purpose. The scope fence says no web UI, and a dashboard that needs a server
is a service you now have to run, secure, and remember to turn off.
"""

from __future__ import annotations

import html
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from kernel.db import connect, migrate  # noqa: E402

OUT = ROOT / "evals" / "dashboard.html"


def _table(rows: list[dict], caption: str) -> str:
    if not rows:
        return f"<h2>{html.escape(caption)}</h2><p class=empty>no data yet</p>"
    cols = list(rows[0])
    head = "".join(f"<th>{html.escape(c)}</th>" for c in cols)
    body = "".join(
        "<tr>" + "".join(f"<td>{html.escape(str(r.get(c, '')))}</td>" for c in cols) + "</tr>"
        for r in rows
    )
    return (f"<h2>{html.escape(caption)}</h2>"
            f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>")


def build(db: Path | str = ROOT / "chingis.db") -> str:
    conn = connect(db)
    migrate(conn)
    q = lambda sql: [dict(r) for r in conn.execute(sql)]

    decisions = q("SELECT verb, COUNT(*) n, ROUND(AVG(confidence),3) avg_conf "
                  "FROM decisions GROUP BY verb ORDER BY n DESC")
    reasons = q("SELECT reason_code, COUNT(*) n, ROUND(AVG(confidence),3) avg_conf "
                "FROM decisions GROUP BY reason_code ORDER BY n DESC LIMIT 20")
    lanes = q("SELECT fleet lane, status, COUNT(*) n FROM contracts "
              "GROUP BY fleet, status ORDER BY lane")
    outcomes = q("SELECT COUNT(*) contracts, SUM(v1_pass) v1_passed, "
                 "ROUND(SUM(cost_usd),4) usd, ROUND(SUM(quota_units),1) quota, "
                 "ROUND(AVG(wall_s),1) avg_wall FROM outcomes")
    events = q("SELECT type, COUNT(*) n FROM events GROUP BY type ORDER BY n DESC")
    cycles = q("SELECT id, started_ts, base_model, promoted, notes FROM cycles ORDER BY id DESC LIMIT 10")

    total = conn.execute("SELECT COUNT(*) n FROM decisions").fetchone()["n"]
    conn.close()

    # M2 needs >=1k logged decisions; showing the distance makes the gate legible.
    m2 = f"{total}/1000 decisions logged ({total / 10:.0f}% of the M2 prerequisite)"

    return f"""<!doctype html><meta charset=utf-8>
<title>Chingis — eval board</title>
<style>
 body{{font:14px/1.5 ui-monospace,monospace;max-width:1000px;margin:2rem auto;padding:0 1rem;
      background:#F2F4F3;color:#191C1B}}
 h1{{font-size:28px;letter-spacing:.02em;text-transform:uppercase}}
 h2{{font-size:12px;letter-spacing:.12em;text-transform:uppercase;color:#666D6A;
     border-bottom:2px solid #191C1B;padding-bottom:4px;margin-top:2rem}}
 table{{border-collapse:collapse;width:100%;background:#FAFBFA}}
 th{{text-align:left;font-size:11px;letter-spacing:.08em;text-transform:uppercase;
     border-bottom:2px solid #191C1B;padding:6px 8px}}
 td{{border-bottom:1px solid #C7CCC9;padding:6px 8px}}
 .empty{{color:#666D6A}} .bar{{background:#E4E9FA;border:1.5px solid #2242C8;padding:8px 12px;margin:1rem 0}}
 @media(prefers-color-scheme:dark){{body{{background:#191C1B;color:#F2F4F3}}
   table{{background:#222624}} td{{border-color:#3A403D}} h2{{border-color:#F2F4F3}}}}
</style>
<h1>Chingis — eval board</h1>
<div class=bar><b>M2 prerequisite:</b> {html.escape(m2)}</div>
{_table(outcomes, "Outcomes")}
{_table(decisions, "Decisions by verb")}
{_table(reasons, "Reason codes (the bandit's raw material)")}
{_table(lanes, "Contracts by lane")}
{_table(events, "Events")}
{_table(cycles, "Improvement cycles")}
<p class=empty>Generated by evals/dashboard.py — static, no server.</p>
"""


if __name__ == "__main__":
    OUT.write_text(build())
    print(f"wrote {OUT}")
